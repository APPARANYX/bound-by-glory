'use strict';
// Keep browser and injected observers on the same canonical implementation.
const fs = require('node:fs');
const path = require('node:path');
const repo = path.join(__dirname, '..');
const inputs = ['scripts/lib/exact-query-census.cjs', 'scripts/battle-hotpath-profiler.cjs'];
const header = `/* Generated by scripts/build-browser-query-census.cjs. Diagnostic only; never reuses native answers. */
// prettier-ignore
(function (root) {
  'use strict';
  if (typeof location === 'undefined') return;
  var q = new URLSearchParams(location.search || '');
  if (q.get('cpuBench') !== '1' || q.get('cpuQueries') !== '1') return;
  root.BattleBrowserQueryCensus = {
    start: function () {
      if (root.BattleHotpathProfiler || root.BattleExactQueryCensus)
        throw new Error('Another query profiler is already installed; reload first.');
      // The canonical helper is UMD; this bundle always selects its browser export.
      var module;
`;
const footer = `
      var profiler = root.BattleHotpathProfiler, helper = root.BattleExactQueryCensus;
      return {
        snapshot: function () { return profiler.snapshot(0); },
        restore: function () {
          profiler.restore();
          if (root.BattleHotpathProfiler === profiler) delete root.BattleHotpathProfiler;
          if (root.BattleExactQueryCensus === helper) delete root.BattleExactQueryCensus;
        }
      };
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;
const output =
  header + inputs.map(file => fs.readFileSync(path.join(repo, file), 'utf8').trim()).join('\n') + footer;
const target = path.join(repo, 'battle/modules/97b-browser-query-census.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Regenerate browser query census bundle');
} else fs.writeFileSync(target, output);
